# Opinion Mining on Product/Service Reviews Dataset

import pandas as pd
import matplotlib.pyplot as plt
from textblob import TextBlob

# Step 1: Create a sample product/service reviews dataset
data = {
    "Review": [
        "This mobile phone is excellent and works perfectly",
        "The product quality is amazing and fantastic",
        "I love this laptop, it is very fast",
        "The camera quality is really good",
        "The delivery service was quick and excellent",
        "This product is terrible and very disappointing",
        "The phone battery is bad and drains quickly",
        "The laptop is slow and the quality is poor",
        "Customer service was rude and unhelpful",
        "The delivery was late and the packaging was damaged",
        "The product is okay and works normally",
        "The service was average, nothing special"
    ]
}

df = pd.DataFrame(data)

# Step 2: Perform sentiment analysis
def get_sentiment(review):
    polarity = TextBlob(review).sentiment.polarity

    if polarity > 0:
        return "Positive"
    elif polarity < 0:
        return "Negative"
    else:
        return "Neutral"

# Step 3: Calculate sentiment and polarity
df["Polarity"] = df["Review"].apply(
    lambda text: TextBlob(text).sentiment.polarity
)

df["Sentiment"] = df["Review"].apply(get_sentiment)

# Step 4: Display the review dataset
print("\nOpinion Mining Results:\n")
print(df.to_string(index=False))

# Step 5: Count each sentiment category
sentiment_counts = df["Sentiment"].value_counts()

print("\nSentiment Summary:")
print(sentiment_counts)

# Step 6: Calculate sentiment percentages
print("\nSentiment Percentages:")
percentages = (
    df["Sentiment"].value_counts(normalize=True) * 100
)

for sentiment, percentage in percentages.items():
    print(f"{sentiment}: {percentage:.2f}%")

# Step 7: Plot sentiment distribution
sentiment_counts.reindex(
    ["Positive", "Negative", "Neutral"],
    fill_value=0
).plot(
    kind="bar",
    title="Customer Review Sentiment Analysis",
    xlabel="Sentiment",
    ylabel="Number of Reviews",
    rot=0
)

plt.tight_layout()
plt.show()

# Step 8: Save the analyzed dataset
df.to_csv("opinion_mining_results.csv", index=False)

print("\nResults saved to opinion_mining_results.csv")