# Commented out IPython magic to ensure Python compatibility.
# %pip install -q scikit-learn

import os
import re
import shutil
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.naive_bayes import MultinomialNB
from sklearn.pipeline import Pipeline
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, classification_report

# 1. Create sample document dataset
documents = [
    ("Artificial intelligence and machine learning are growing fields.", "Technology"),
    ("Python programming is used to build software applications.", "Technology"),
    ("Neural networks are widely used in deep learning.", "Technology"),
    ("The new smartphone uses an advanced computer processor.", "Technology"),
    ("Software developers write code to solve problems.", "Technology"),

    ("The team won the cricket match yesterday.", "Sports"),
    ("Football players trained before the final tournament.", "Sports"),
    ("The athlete won a gold medal in the competition.", "Sports"),
    ("India played well in the cricket world cup.", "Sports"),
    ("The coach prepared the team for the next match.", "Sports"),

    ("The stock market showed growth this week.", "Business"),
    ("The company reported an increase in annual profits.", "Business"),
    ("Investors analyze financial reports before investing.", "Business"),
    ("The business launched a new product in the market.", "Business"),
    ("The bank announced changes in interest rates.", "Business"),

    ("Students are preparing for their university examinations.", "Education"),
    ("The teacher explained the mathematics lesson.", "Education"),
    ("Online learning provides access to educational resources.", "Education"),
    ("The college organized a science exhibition.", "Education"),
    ("Libraries help students improve their knowledge.", "Education")
]

X = [item[0] for item in documents]
y = [item[1] for item in documents]

# 2. Split dataset
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.25, random_state=42, stratify=y
)

# 3. Build TF-IDF + Naive Bayes model
model = Pipeline([
    ("tfidf", TfidfVectorizer(stop_words="english")),
    ("classifier", MultinomialNB())
])

# 4. Train model
model.fit(X_train, y_train)

# 5. Evaluate model
predictions = model.predict(X_test)

print("DOCUMENT CLASSIFICATION RESULTS")
print("-" * 40)
print("Accuracy:", round(accuracy_score(y_test, predictions) * 100, 2), "%")
print("\nClassification Report:\n")
print(classification_report(y_test, predictions, zero_division=0))

# 6. Create folders for document categories
base_dir = "classified_documents"
os.makedirs(base_dir, exist_ok=True)

categories = ["Technology", "Sports", "Business", "Education"]

for category in categories:
    os.makedirs(os.path.join(base_dir, category), exist_ok=True)

# 7. Classify and separate sample documents
print("\nDOCUMENT SEPARATION")
print("-" * 40)

for i, document in enumerate(X, start=1):
    predicted_category = model.predict([document])[0]

    # Save each document in its predicted category folder
    file_path = os.path.join(
        base_dir,
        predicted_category,
        f"document_{i}.txt"
    )

    with open(file_path, "w", encoding="utf-8") as file:
        file.write(document)

    print(f"Document {i}: {predicted_category}")

print("\nDocuments classified and separated successfully!")
print("Output folder:", os.path.abspath(base_dir))