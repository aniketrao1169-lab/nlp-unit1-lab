# Commented out IPython magic to ensure Python compatibility.
# %pip install -q transformers torch

from transformers import pipeline

# Load pre-trained BART summarization model
summarizer = pipeline(
    "summarization",
    model="facebook/bart-large-cnn"
)

# Input document
text = """
Artificial Intelligence is one of the most important technologies
in the modern world. It enables computers to perform tasks that
normally require human intelligence. These tasks include learning,
problem-solving, language understanding, and image recognition.

Machine learning is a part of artificial intelligence that allows
systems to learn from data. Deep learning uses neural networks to
solve complex problems. AI is widely used in healthcare, education,
agriculture, transportation, and business.

In healthcare, AI helps doctors analyze medical images and support
disease diagnosis. In education, AI provides personalized learning
experiences. In agriculture, AI helps monitor crops and improve
productivity. Although AI offers many benefits, responsible use,
privacy, and data security remain important concerns.
"""

# Generate summary
summary = summarizer(
    text,
    max_length=100,
    min_length=30,
    do_sample=False,
    truncation=True
)

# Display output
print("ORIGINAL TEXT:\n")
print(text)

print("\nGENERATED SUMMARY:\n")
print(summary[0]["summary_text"])

print("\nSummarization completed successfully!")