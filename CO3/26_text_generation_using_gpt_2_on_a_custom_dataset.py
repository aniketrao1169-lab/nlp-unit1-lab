# Commented out IPython magic to ensure Python compatibility.
# %pip install -q transformers datasets torch

import torch
from datasets import Dataset
from transformers import (
    GPT2Tokenizer,
    GPT2LMHeadModel,
    Trainer,
    TrainingArguments,
    DataCollatorForLanguageModeling
)

# 1. Create custom dataset
texts = [
    "Artificial Intelligence is transforming the world.",
    "Machine learning helps computers learn from data.",
    "Deep learning uses neural networks.",
    "Natural Language Processing helps computers understand human language.",
    "GPT-2 is a transformer-based text generation model.",
    "Python is widely used in artificial intelligence.",
    "AI is useful in education, healthcare, and agriculture.",
    "Text generation is an important application of NLP.",
    "Data science helps analyze large amounts of information.",
    "Neural networks are inspired by the human brain."
]

dataset = Dataset.from_dict({"text": texts})

# 2. Load GPT-2 tokenizer and model
model_name = "gpt2"

tokenizer = GPT2Tokenizer.from_pretrained(model_name)
model = GPT2LMHeadModel.from_pretrained(model_name)

tokenizer.pad_token = tokenizer.eos_token
model.config.pad_token_id = tokenizer.eos_token_id

# 3. Tokenize dataset
def tokenize_function(examples):
    return tokenizer(
        examples["text"],
        truncation=True,
        max_length=64
    )

tokenized_dataset = dataset.map(
    tokenize_function,
    batched=True,
    remove_columns=["text"]
)

# 4. Prepare language modeling data
data_collator = DataCollatorForLanguageModeling(
    tokenizer=tokenizer,
    mlm=False
)

# 5. Configure training
training_args = TrainingArguments(
    output_dir="./gpt2_results",
    num_train_epochs=3,
    per_device_train_batch_size=2,
    learning_rate=5e-5,
    logging_steps=1,
    save_strategy="no",
    report_to="none",
    use_cpu=not torch.cuda.is_available()
)

# 6. Fine-tune GPT-2
trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=tokenized_dataset,
    data_collator=data_collator
)

print("Training GPT-2...")
trainer.train()

# 7. Generate text
prompt = "Artificial Intelligence"

device = next(model.parameters()).device
inputs = tokenizer(prompt, return_tensors="pt").to(device)

output = model.generate(
    **inputs,
    max_new_tokens=40,
    do_sample=True,
    temperature=0.8,
    top_k=50,
    pad_token_id=tokenizer.eos_token_id
)

generated_text = tokenizer.decode(
    output[0],
    skip_special_tokens=True
)

print("\nInput Prompt:", prompt)
print("\nGenerated Text:", generated_text)

# 8. Save fine-tuned model
trainer.save_model("./fine_tuned_gpt2")
tokenizer.save_pretrained("./fine_tuned_gpt2")

print("\nFine-tuned GPT-2 model saved successfully!")