import tensorflow as tf
from tensorflow.keras.layers import Input, Dense, Softmax
from tensorflow.keras.models import Model

# Sample sequence: 3 words, each with 4 features
inputs = Input(shape=(3, 4))

# Calculate attention scores
scores = Dense(1, activation="tanh")(inputs)

# Convert scores into attention weights
weights = Softmax(axis=1)(scores)

# Apply attention weights to input sequence
weighted_output = tf.keras.layers.Multiply()([inputs, weights])

# Sum weighted representations
context = tf.keras.layers.Lambda(
    lambda x: tf.reduce_sum(x, axis=1)
)(weighted_output)

# Create model
model = Model(inputs=inputs, outputs=context)

# Sample input
data = tf.random.normal((1, 3, 4))

# Get output
output = model.predict(data, verbose=0)

print("Input Shape:", data.shape)
print("Output Shape:", output.shape)
print("Context Vector:\n", output)