# Commented out IPython magic to ensure Python compatibility.
# %pip install -q transformers torch

import torch
from transformers import AutoTokenizer, AutoModelForCausalLM

# Load pre-trained DialoGPT model
model_name = "microsoft/DialoGPT-small"

tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForCausalLM.from_pretrained(model_name)

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model.to(device)
model.eval()

print("DialoGPT Chatbot is ready!")
print("Type 'exit' to stop the conversation.\n")

chat_history_ids = None

# Start conversation
while True:
    user_input = input("You: ").strip()

    if user_input.lower() in ["exit", "quit", "bye"]:
        print("Bot: Goodbye! Have a nice day.")
        break

    if not user_input:
        continue

    # Encode user input
    new_input_ids = tokenizer.encode(
        user_input + tokenizer.eos_token,
        return_tensors="pt"
    ).to(device)

    # Append conversation history
    bot_input_ids = (
        torch.cat([chat_history_ids, new_input_ids], dim=-1)
        if chat_history_ids is not None
        else new_input_ids
    )

    # Generate response
    with torch.no_grad():
        chat_history_ids = model.generate(
            bot_input_ids,
            max_new_tokens=60,
            pad_token_id=tokenizer.eos_token_id,
            do_sample=True,
            top_k=50,
            top_p=0.92,
            temperature=0.75,
            repetition_penalty=1.2
        )

    # Extract bot response
    response_ids = chat_history_ids[:, bot_input_ids.shape[-1]:]
    response = tokenizer.decode(
        response_ids[0],
        skip_special_tokens=True
    )

    print("Bot:", response if response.strip() else "I am not sure. Can you say that another way?")