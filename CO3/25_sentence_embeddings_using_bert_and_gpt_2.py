import torch
from transformers import AutoTokenizer, AutoModel

# Sample sentences
sentences = [
    "Artificial intelligence is changing the world.",
    "AI is transforming our lives."
]

# Load BERT
bert_name = "google-bert/bert-base-uncased"
bert_tokenizer = AutoTokenizer.from_pretrained(bert_name)
bert_model = AutoModel.from_pretrained(bert_name)

# Load GPT-2
gpt_name = "openai-community/gpt2"
gpt_tokenizer = AutoTokenizer.from_pretrained(gpt_name)
gpt_model = AutoModel.from_pretrained(gpt_name)

# GPT-2 has no default padding token
gpt_tokenizer.pad_token = gpt_tokenizer.eos_token
gpt_model.config.pad_token_id = gpt_tokenizer.pad_token_id

def get_embeddings(sentences, tokenizer, model):
    inputs = tokenizer(
        sentences,
        padding=True,
        truncation=True,
        max_length=128,
        return_tensors="pt"
    )

    with torch.no_grad():
        outputs = model(**inputs)

    # Mean pooling, excluding padding tokens
    token_embeddings = outputs.last_hidden_state
    mask = inputs["attention_mask"].unsqueeze(-1)

    embeddings = (token_embeddings * mask).sum(dim=1)
    embeddings = embeddings / mask.sum(dim=1).clamp(min=1)

    return embeddings

bert_embeddings = get_embeddings(
    sentences, bert_tokenizer, bert_model
)

gpt2_embeddings = get_embeddings(
    sentences, gpt_tokenizer, gpt_model
)

print("BERT Embeddings Shape:", bert_embeddings.shape)
print("GPT-2 Embeddings Shape:", gpt2_embeddings.shape)

# Cosine similarity between the two sentences
bert_similarity = torch.nn.functional.cosine_similarity(
    bert_embeddings[0].unsqueeze(0),
    bert_embeddings[1].unsqueeze(0)
)

gpt2_similarity = torch.nn.functional.cosine_similarity(
    gpt2_embeddings[0].unsqueeze(0),
    gpt2_embeddings[1].unsqueeze(0)
)

print("BERT Similarity:", bert_similarity.item())
print("GPT-2 Similarity:", gpt2_similarity.item())