from transformers import MarianMTModel, MarianTokenizer

# Load pre-trained English-to-French translation model
model_name = "Helsinki-NLP/opus-mt-en-fr"

tokenizer = MarianTokenizer.from_pretrained(model_name)
model = MarianMTModel.from_pretrained(model_name)

# Input English sentences
sentences = [
    "Hello, how are you?",
    "Artificial Intelligence is changing the world.",
    "I am learning Natural Language Processing.",
    "Machine translation helps people communicate."
]

# Tokenize input sentences
inputs = tokenizer(
    sentences,
    return_tensors="pt",
    padding=True,
    truncation=True
)

# Generate translations
translated = model.generate(**inputs)

# Decode translated output
translations = tokenizer.batch_decode(
    translated,
    skip_special_tokens=True
)

# Display results
print("MACHINE TRANSLATION: ENGLISH TO FRENCH\n")

for i, sentence in enumerate(sentences):
    print("English:", sentence)
    print("French :", translations[i])
    print("-" * 50)

print("Translation completed successfully!")